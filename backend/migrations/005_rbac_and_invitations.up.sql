ALTER TABLE platform_admins
  MODIFY COLUMN role ENUM('operations','super_admin','support','custom') NOT NULL DEFAULT 'operations',
  ADD COLUMN role_id CHAR(26) NULL AFTER role,
  ADD KEY ix_platform_admins_role_id (role_id),
  ADD CONSTRAINT fk_platform_admins_role FOREIGN KEY (role_id) REFERENCES rbac_roles(id) ON DELETE RESTRICT;

UPDATE platform_admins a JOIN rbac_roles r ON r.role_key = a.role SET a.role_id = r.id WHERE a.role_id IS NULL;

-- Admin-created customer accounts are activated through a single-use invitation.
-- Only a SHA-256 digest of the token is stored; the raw token exists only in the emailed link.
CREATE TABLE account_invitations (
  id CHAR(26) NOT NULL PRIMARY KEY,
  user_id CHAR(26) NOT NULL,
  email VARCHAR(254) NOT NULL,
  tenant_id CHAR(26) NULL,
  membership_role ENUM('owner','admin','mailbox_user','billing') NULL,
  mailbox_id CHAR(26) NULL,
  send_mailbox_info TINYINT(1) NOT NULL DEFAULT 0,
  token_hash CHAR(64) NULL,
  status ENUM('pending','consumed','revoked','expired') NOT NULL DEFAULT 'pending',
  delivery ENUM('not_sent','queued','sent','failed') NOT NULL DEFAULT 'not_sent',
  last_email_id CHAR(26) NULL,
  resend_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_sent_at DATETIME(3) NULL,
  expires_at DATETIME(3) NOT NULL,
  consumed_at DATETIME(3) NULL,
  revoked_at DATETIME(3) NULL,
  created_by_admin_id CHAR(26) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_account_invitations_token (token_hash),
  KEY ix_account_invitations_user (user_id, status),
  KEY ix_account_invitations_status (status, expires_at),
  KEY ix_account_invitations_mailbox (mailbox_id),
  CONSTRAINT fk_ai_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_ai_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Durable outgoing platform email with delivery state, bounded retries and de-duplication.
-- The payload (template parameters, which may include a one-time link) is encrypted at rest and cleared after sending.
CREATE TABLE email_outbox (
  id CHAR(26) NOT NULL PRIMARY KEY,
  kind VARCHAR(40) NOT NULL,
  to_email VARCHAR(254) NOT NULL,
  payload_encrypted TEXT NULL,
  status ENUM('queued','sending','sent','failed','cancelled') NOT NULL DEFAULT 'queued',
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NOT NULL DEFAULT 6,
  next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  locked_until DATETIME(3) NULL,
  last_error VARCHAR(500) NULL,
  dedupe_key VARCHAR(120) NOT NULL,
  related_type VARCHAR(30) NULL,
  related_id CHAR(26) NULL,
  tenant_id CHAR(26) NULL,
  created_by_admin_id CHAR(26) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  sent_at DATETIME(3) NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_email_outbox_dedupe (dedupe_key),
  KEY ix_email_outbox_due (status, next_attempt_at),
  KEY ix_email_outbox_related (related_type, related_id),
  KEY ix_email_outbox_created (created_at)
) ENGINE=InnoDB;
