-- RBAC: normalized permission catalog, roles and role->permission links for platform staff.
-- Additive and backward compatible: platform_admins.role is kept; role_id is backfilled from it.

CREATE TABLE rbac_permissions (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  resource VARCHAR(40) NOT NULL,
  action VARCHAR(40) NOT NULL,
  description VARCHAR(200) NOT NULL,
  is_sensitive TINYINT(1) NOT NULL DEFAULT 0,
  KEY ix_rbac_permissions_resource (resource)
) ENGINE=InnoDB;

CREATE TABLE rbac_roles (
  id CHAR(26) NOT NULL PRIMARY KEY,
  role_key VARCHAR(48) NOT NULL,
  name VARCHAR(80) NOT NULL,
  description VARCHAR(300) NOT NULL DEFAULT '',
  is_system TINYINT(1) NOT NULL DEFAULT 0,
  created_by CHAR(26) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_rbac_roles_key (role_key),
  UNIQUE KEY uq_rbac_roles_name (name)
) ENGINE=InnoDB;

CREATE TABLE rbac_role_permissions (
  role_id CHAR(26) NOT NULL,
  permission_id VARCHAR(64) NOT NULL,
  PRIMARY KEY (role_id, permission_id),
  KEY ix_rrp_permission (permission_id),
  CONSTRAINT fk_rrp_role FOREIGN KEY (role_id) REFERENCES rbac_roles(id) ON DELETE CASCADE,
  CONSTRAINT fk_rrp_permission FOREIGN KEY (permission_id) REFERENCES rbac_permissions(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

